"""Experiments behind the articles' findings.

    python -m experiments.run_experiments           # under a minute; writes experiments/results/

E1  Static probes against an adaptive attacker: success grows with the attacker's budget.
E2  Defence in depth: every layer alone, all layers, and all layers but one.
E3  What "0 successes" proves: upper bounds, and the chance of seeing zero when attacks do work.
E4  The input filter's trade-off: attacks blocked against legitimate requests refused.
E5  Which mutations get past which layer.
"""
from __future__ import annotations

import json
import random
import sys
from dataclasses import replace
from pathlib import Path

from seclab.app import Defences
from seclab.attacks import MUTATIONS, SEEDS, adaptive
from seclab.measure import LAYER_TARGETS, campaign, isolate, rule_of_three, utility

OUT = Path(__file__).parent / "results"
R = Defences.recommended()


def e1_adaptive(trials: int = 100) -> dict:
    d = replace(R, secret_in_prompt=True)          # all other defences on; the secret is in the prompt
    rows = []
    for budget in (1, 3, 6, 10, 30):
        rng = random.Random(budget)
        wins = sum(adaptive("leak_secret", ch, d, rng, budget)[0] for _ in range(trials) for ch in ("direct", "indirect"))
        rows.append({"attacker_tries": budget, "secret_leaked_in_share_of_runs": round(wins / (2 * trials), 3)})
    static = campaign(d, repeats=20)["by_goal"]["leak_secret"][0]
    return {"static_suite_success_rate": round(static, 3), "rows": rows, "trials": trials}


def e2_layers() -> dict:
    configs = {"no defences": Defences.none(), "all layers (recommended)": R}
    for layer in LAYER_TARGETS:
        configs[f"only {layer}"] = isolate(R, layer)
    for layer in LAYER_TARGETS:
        off = {"input_filter": "off", "secret_in_prompt": True}.get(layer, False)
        configs[f"all but {layer}"] = replace(R, **{layer: off})
    rows = []
    for label, d in configs.items():
        c = campaign(d, repeats=20)
        rows.append({"configuration": label, "attack_success": round(c["overall"][0], 3),
                     "goals_still_succeeding": ", ".join(g for g, v in c["by_goal"].items() if v[0] > 0) or "none",
                     "legit_refused": round(utility(d)["false_refusal_rate"], 2)})
    return {"rows": rows}


def e3_zero_successes() -> dict:
    rows = []
    for n in (30, 100, 300, 1000, 3000):
        row = {"attempts_with_0_successes": n, "upper_bound_95": f"{rule_of_three(n):.2%}"}
        for r in (0.005, 0.01, 0.02):
            row[f"chance_of_0_if_true_rate_{r:.1%}"] = round((1 - r) ** n, 3)
        rows.append(row)
    return {"rows": rows}


def e4_filter() -> dict:
    rows = []
    for level in ("off", "low", "medium", "high"):
        alone = campaign(replace(Defences.none(), input_filter=level), repeats=20)
        stopped = alone["stopped_by"].get("input_filter", 0) / alone["attempts"]
        with_others = campaign(replace(R, input_filter=level), repeats=20)["overall"][0]
        u = utility(replace(R, input_filter=level))
        rows.append({"input_filter": level, "attacks_it_blocks": round(stopped, 3),
                     "success_with_all_other_layers": round(with_others, 4),
                     "legit_refused": round(u["false_refusal_rate"], 2), "tricky_legit_refused": round(u["tricky_refused"], 2)})
    return {"rows": rows}


def e5_mutations() -> dict:
    rows = []
    setups = {"filter (medium) only": replace(Defences.none(), input_filter="medium"),
              "hardening only": isolate(R, "hardening"), "no defences": Defences.none()}
    results = {k: campaign(d, repeats=20)["by_mutation"] for k, d in setups.items()}
    for m in MUTATIONS:
        rows.append({"mutation": m, **{f"success_{k}": round(results[k][m][0], 2) for k in setups}})
    return {"rows": rows}


def table(rows: list[dict]) -> list[str]:
    cols = list(rows[0])
    return ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] + \
           ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]


def main() -> int:
    res = {"E1": e1_adaptive(), "E2": e2_layers(), "E3": e3_zero_successes(), "E4": e4_filter(), "E5": e5_mutations()}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "experiments.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    L = ["# Experiment results", "", "Generated by `python -m experiments.run_experiments`. Deterministic: rerunning gives the same numbers.", "",
         f"## E1. Static suite against an adaptive attacker (secret in the prompt, all other layers on; "
         f"static suite success rate {res['E1']['static_suite_success_rate']}; {res['E1']['trials']} runs per channel)", ""] + table(res["E1"]["rows"])
    L += ["", "## E2. Defence in depth (static suite, 20 repeats)", ""] + table(res["E2"]["rows"])
    L += ["", "## E3. What zero observed successes proves", ""] + table(res["E3"]["rows"])
    L += ["", "## E4. Input filter sensitivity", ""] + table(res["E4"]["rows"])
    L += ["", "## E5. Mutations against single layers (attack success)", ""] + table(res["E5"]["rows"])
    (OUT / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
